  document.getElementById("languageMenu");

const languageLabel =
  document.getElementById("languageLabel");


function buildLanguageMenu() {

  if (!languageMenu) return;

  languageMenu.innerHTML = "";

  languageOrder.forEach((code) => {

    const language =
      translations[code];

    if (!language) return;

    const button =
      document.createElement("button");

    button.type = "button";

    button.dataset.language = code;

    button.textContent =
      language.languageName;

    languageMenu.appendChild(button);

  });

}


/* =====================================================
   TRANSLATE PAGE
===================================================== */

function applyLanguage(languageCode) {

  const language =
    translations[languageCode];

  if (!language) return;

  document.documentElement.lang =
    languageCode;

  document.documentElement.dir =
    languageCode === "ar"
      ? "rtl"
      : "ltr";


  document.querySelectorAll("[data-i18n]")
    .forEach((element) => {

      const key =
        element.dataset.i18n;

      if (
        language[key] === undefined
      ) {
        return;
      }

      const translatedText =
        language[key];

      const styledSpan =
        element.querySelector(":scope > span");


      if (styledSpan) {

        const words =
          translatedText.split(" ");

        const splitPoint =
          Math.max(
            1,
            Math.ceil(words.length * 0.65)
          );

        const firstPart =
          words
            .slice(0, splitPoint)
            .join(" ");

        const secondPart =
          words
            .slice(splitPoint)
            .join(" ");


        element.childNodes.forEach(
          (node) => {

            if (
              node.nodeType ===
              Node.TEXT_NODE
            ) {

              node.textContent = "";

            }

          }
        );


        const textNode =
          document.createTextNode(
            firstPart + " "
          );

        element.insertBefore(
          textNode,
          styledSpan
        );


        styledSpan.textContent =
          secondPart;

      } else {

        element.textContent =
          translatedText;

      }

    });


  if (languageLabel) {

    languageLabel.textContent =
      language.languageName;

  }


  document.querySelectorAll(
    "#languageMenu button"
  ).forEach((button) => {

    button.classList.toggle(
      "active",
      button.dataset.language === languageCode
    );

  });


  localStorage.setItem(
    "godzyaLanguage",
    languageCode
  );

}

/* =====================================================
   LANGUAGE SELECTION
===================================================== */

function setLanguage(languageCode) {

  if (!translations[languageCode]) {

    languageCode = "en";

  }

  applyLanguage(languageCode);

}


